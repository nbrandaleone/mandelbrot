/**
 * Mandelbrot Set Viewer — Frontend Application (app.js)
 * =====================================================
 * This ES Module connects the HTML5 <canvas> and keyboard controls to our
 * Rust/WebAssembly Mandelbrot renderer compiled into `./pkg/mandelbrot.js`.
 *
 * How the pieces fit together:
 *   1. `init()` fetches and compiles `mandelbrot_bg.wasm` in the browser.
 *   2. Whenever the view changes (window resize, pan, zoom, reset), we call
 *      `render_mandelbrot(width, height, centerX, centerY, zoom, maxIter)`.
 *   3. Rust computes the Mandelbrot escape-time formula for every pixel and
 *      returns a flat `Uint8Array` of RGBA color bytes: [R, G, B, A, R, G, B, A, ...].
 *   4. We wrap those bytes in an `ImageData` object and paint them onto the
 *      2D canvas context with `ctx.putImageData(...)`.
 */

// Import the wasm-bindgen glue code generated by `wasm-pack build --target web`.
// - `init` (default export): async function that loads and instantiates the .wasm binary.
// - `render_mandelbrot`: our exported Rust function that computes the fractal pixels.
import init, { render_mandelbrot } from './pkg/mandelbrot.js';

// ---------------------------------------------------------------------------
// Configuration & Default View
// ---------------------------------------------------------------------------

// Default camera position in the complex plane.
// The Mandelbrot set lives roughly within x ∈ [-2.0, 0.7] and y ∈ [-1.2, 1.2],
// so centering at (-0.5, 0.0) frames the whole fractal nicely.
const DEFAULT_VIEW = Object.freeze({
  centerX: -0.5,
  centerY: 0.0,
  zoom: 1.0,
});

// At zoom = 1.0, the shorter edge of the canvas spans 3.2 units in the complex plane
// (matching the coordinate mapping in src/lib.rs).
const BASE_VIEW_SPAN = 3.2;

// Iteration limits: deeper zooms reveal finer boundary detail and benefit from
// more iterations, while capping prevents frames from becoming too slow.
const BASE_MAX_ITER = 256;
const MAX_ALLOWED_ITER = 2000;

// Zoom bounds: 64-bit floating-point numbers (`f64`) lose precision around ~1e13x zoom.
const MIN_ZOOM = 0.25;
const MAX_ZOOM = 1e13;

// Keyboard responsiveness constants:
// - TAP_* values give crisp, immediate feedback on a single keypress.
// - HOLD_* values drive smooth continuous motion per second while a key is held.
const TAP_PAN_FRACTION = 0.06;     // Move 6% of the visible span on initial tap
const HOLD_PAN_PER_SEC = 0.65;     // Move 65% of the visible span per second when held
const TAP_ZOOM_FACTOR = 1.15;      // 15% zoom step on initial tap
const HOLD_ZOOM_RATE = 2.4;        // 2.4x zoom change per second when held

// ---------------------------------------------------------------------------
// DOM References
// ---------------------------------------------------------------------------

const canvas = document.getElementById('mandelbrot-canvas');
const ctx = canvas.getContext('2d');

const hudEl = document.getElementById('hud');
const hudHintEl = document.getElementById('hud-hint');
const statusOverlayEl = document.getElementById('status-overlay');
const statusCardEl = statusOverlayEl.querySelector('.status-card');
const statusMessageEl = document.getElementById('status-message');

const statXEl = document.getElementById('stat-x');
const statYEl = document.getElementById('stat-y');
const statZoomEl = document.getElementById('stat-zoom');
const statIterEl = document.getElementById('stat-iter');
const statTimeEl = document.getElementById('stat-time');

// ---------------------------------------------------------------------------
// Application State
// ---------------------------------------------------------------------------

// Current camera state in the complex plane.
const view = {
  centerX: DEFAULT_VIEW.centerX,
  centerY: DEFAULT_VIEW.centerY,
  zoom: DEFAULT_VIEW.zoom,
};

// Tracks which navigation/zoom actions are currently held down.
// Using logical action names ('left', 'right', 'up', 'down', 'zoomIn', 'zoomOut')
// keeps key handling clean even when multiple keys map to the same action.
const activeActions = new Set();

let wasmReady = false;
let animationFrameId = null;
let lastFrameTime = 0;

// ---------------------------------------------------------------------------
// Rendering Pipeline (WASM -> Canvas ImageData)
// ---------------------------------------------------------------------------

/**
 * Computes an appropriate iteration limit for the current zoom level.
 * As you zoom deeper, the fractal boundary gets more intricate, so scaling
 * iterations logarithmically with zoom keeps edges sharp.
 */
function computeMaxIterations(zoom) {
  const extra = Math.max(0, Math.log2(zoom)) * 55;
  return Math.min(MAX_ALLOWED_ITER, Math.round(BASE_MAX_ITER + extra));
}

/**
 * Synchronizes the canvas's internal pixel buffer with the browser window size.
 * We match CSS pixels (1:1) so real-time keyboard panning and zooming stays
 * responsive even on high-DPI displays.
 */
function resizeCanvas() {
  const width = Math.max(1, Math.floor(window.innerWidth));
  const height = Math.max(1, Math.floor(window.innerHeight));

  if (canvas.width !== width || canvas.height !== height) {
    canvas.width = width;
    canvas.height = height;
  }
}

/**
 * Calls the Rust/WASM renderer and paints the resulting RGBA pixels onto the canvas.
 */
function render() {
  if (!wasmReady) return;

  const width = canvas.width;
  const height = canvas.height;
  const maxIter = computeMaxIterations(view.zoom);

  const startMs = performance.now();

  // 1. Call into WebAssembly: Rust computes the Mandelbrot set and returns a
  //    Uint8Array of length (width * height * 4), storing [R, G, B, A] per pixel.
  const pixels = render_mandelbrot(
    width,
    height,
    view.centerX,
    view.centerY,
    view.zoom,
    maxIter
  );

  // 2. Canvas `ImageData` requires a `Uint8ClampedArray` (values clamped to 0..255).
  //    Passing (pixels.buffer, pixels.byteOffset, pixels.byteLength) creates a
  //    lightweight view over the exact same underlying bytes without copying them.
  const clamped = new Uint8ClampedArray(
    pixels.buffer,
    pixels.byteOffset,
    pixels.byteLength
  );
  const imageData = new ImageData(clamped, width, height);

  // 3. Blit the entire pixel buffer onto the 2D canvas at top-left (0, 0).
  ctx.putImageData(imageData, 0, 0);

  const elapsedMs = performance.now() - startMs;
  updateHud(maxIter, elapsedMs);
}

/**
 * Updates the HUD numbers to reflect the current center, zoom, iterations,
 * and how many milliseconds the last WASM render took.
 */
function updateHud(maxIter, elapsedMs) {
  // Show more decimal places as we zoom in so tiny coordinate steps remain visible.
  const decimals = Math.min(12, Math.max(6, Math.ceil(Math.log10(view.zoom + 1)) + 5));

  statXEl.textContent = view.centerX.toFixed(decimals);
  statYEl.textContent = view.centerY.toFixed(decimals);
  statZoomEl.textContent = formatZoom(view.zoom);
  statIterEl.textContent = String(maxIter);
  statTimeEl.textContent = `${elapsedMs.toFixed(1)} ms`;
}

/**
 * Formats the zoom multiplier cleanly (e.g., "1.00×", "42.5×", or "1.25e+5×").
 */
function formatZoom(zoom) {
  if (zoom >= 1e5) {
    return `${zoom.toExponential(2)}×`;
  }
  if (zoom >= 100) {
    return `${zoom.toFixed(0)}×`;
  }
  return `${zoom.toFixed(2)}×`;
}

// ---------------------------------------------------------------------------
// View Manipulation & Smooth Animation Loop
// ---------------------------------------------------------------------------

/**
 * Applies a pan and/or zoom delta to the current view state.
 * Notice that panning is divided by `view.zoom`: when zoomed in 100×, each step
 * moves 1/100th as far in the complex plane so navigation feels constant on screen.
 */
function applyMovement(panStep, zoomMultiplier) {
  const currentSpan = BASE_VIEW_SPAN / view.zoom;
  let changed = false;

  // Rust coordinate convention: +X moves right, +Y moves up.
  if (activeActions.has('left')) {
    view.centerX -= panStep * currentSpan;
    changed = true;
  }
  if (activeActions.has('right')) {
    view.centerX += panStep * currentSpan;
    changed = true;
  }
  if (activeActions.has('up')) {
    view.centerY += panStep * currentSpan;
    changed = true;
  }
  if (activeActions.has('down')) {
    view.centerY -= panStep * currentSpan;
    changed = true;
  }

  if (activeActions.has('zoomIn')) {
    view.zoom = Math.min(MAX_ZOOM, view.zoom * zoomMultiplier);
    changed = true;
  }
  if (activeActions.has('zoomOut')) {
    view.zoom = Math.max(MIN_ZOOM, view.zoom / zoomMultiplier);
    changed = true;
  }

  return changed;
}

/**
 * Resets the camera back to the default full-set view and re-renders.
 */
function resetView() {
  view.centerX = DEFAULT_VIEW.centerX;
  view.centerY = DEFAULT_VIEW.centerY;
  view.zoom = DEFAULT_VIEW.zoom;
  render();
}

/**
 * Toggles the visibility of the HUD overlay (bound to the 'H' key).
 */
function toggleHud() {
  const isHidden = hudEl.classList.toggle('hidden');
  hudHintEl.classList.toggle('hidden', !isHidden);
}

/**
 * Runs on every display refresh via `requestAnimationFrame` while at least one
 * movement or zoom key is held down, producing smooth frame-rate-independent motion.
 */
function animationStep(now) {
  if (activeActions.size === 0) {
    animationFrameId = null;
    return;
  }

  // Elapsed time in seconds since the previous frame (clamped to avoid huge jumps
  // if the browser tab was briefly backgrounded).
  const dt = Math.min(0.1, (now - lastFrameTime) / 1000);
  lastFrameTime = now;

  if (dt > 0) {
    const panStep = HOLD_PAN_PER_SEC * dt;
    const zoomMultiplier = Math.pow(HOLD_ZOOM_RATE, dt);
    if (applyMovement(panStep, zoomMultiplier)) {
      render();
    }
  }

  animationFrameId = requestAnimationFrame(animationStep);
}

/**
 * Starts the `requestAnimationFrame` loop if it is not already running.
 */
function ensureAnimationLoop() {
  if (animationFrameId === null) {
    lastFrameTime = performance.now();
    animationFrameId = requestAnimationFrame(animationStep);
  }
}

// ---------------------------------------------------------------------------
// Keyboard Controls
// ---------------------------------------------------------------------------

/**
 * Maps a KeyboardEvent's `key` to one of our continuous navigation actions,
 * or returns `null` if the key is not a pan/zoom control.
 */
function mapKeyToAction(key) {
  switch (key) {
    case 'ArrowUp':
    case 'w':
    case 'W':
      return 'up';
    case 'ArrowDown':
    case 's':
    case 'S':
      return 'down';
    case 'ArrowLeft':
    case 'a':
    case 'A':
      return 'left';
    case 'ArrowRight':
    case 'd':
    case 'D':
      return 'right';
    case '+':
    case '=':
    case 'z':
    case 'Z':
      return 'zoomIn';
    case '-':
    case '_':
    case 'x':
    case 'X':
      return 'zoomOut';
    default:
      return null;
  }
}

window.addEventListener('keydown', (event) => {
  // Don't hijack browser shortcuts like Cmd+R (reload) or Ctrl+Plus (page zoom).
  if (event.metaKey || event.ctrlKey || event.altKey) {
    return;
  }

  // Always prevent arrow keys from scrolling the page.
  if (event.key.startsWith('Arrow')) {
    event.preventDefault();
  }

  // One-shot commands: reset view (R or 0) and toggle HUD (H).
  if (event.key === 'r' || event.key === 'R' || event.key === '0') {
    event.preventDefault();
    resetView();
    return;
  }
  if (event.key === 'h' || event.key === 'H') {
    event.preventDefault();
    toggleHud();
    return;
  }

  // Continuous pan/zoom controls.
  const action = mapKeyToAction(event.key);
  if (!action) return;

  event.preventDefault();

  // On the initial press (not an OS key-repeat event), apply an immediate step
  // so single taps feel snappy, then start the smooth loop while the key stays held.
  if (!activeActions.has(action)) {
    activeActions.add(action);
    if (applyMovement(TAP_PAN_FRACTION, TAP_ZOOM_FACTOR)) {
      render();
    }
    ensureAnimationLoop();
  }
});

window.addEventListener('keyup', (event) => {
  const action = mapKeyToAction(event.key);
  if (action) {
    activeActions.delete(action);
  }
});

// Clear held keys if the window loses focus so movement never gets "stuck".
window.addEventListener('blur', () => {
  activeActions.clear();
});

// Re-size and re-render whenever the browser window changes dimensions.
window.addEventListener('resize', () => {
  resizeCanvas();
  render();
});

// ---------------------------------------------------------------------------
// Initialization
// ---------------------------------------------------------------------------

/**
 * Loads the WebAssembly binary, sizes the canvas, and draws the initial fractal.
 */
async function start() {
  try {
    // Load and instantiate `www/pkg/mandelbrot_bg.wasm`.
    await init();
    wasmReady = true;

    resizeCanvas();
    render();

    // Hide the loading banner now that the first frame is on screen.
    statusOverlayEl.classList.add('hidden');
  } catch (err) {
    console.error('Failed to initialize Mandelbrot WASM module:', err);
    statusCardEl.classList.add('error');
    statusMessageEl.textContent =
      'Failed to load WebAssembly module. Make sure you built the project and are serving www/ over HTTP (e.g. `make run`).';
  }
}

start();
